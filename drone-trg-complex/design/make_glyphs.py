"""Extract Arial Bold outlines for the title as flattened polygons (cap height = 1.0).

Writes glyphs_arialbd.py with GLYPHS = {char: [advance, [[outer, [hole, ...]], ...]]}.
Polygons only; no font is needed at build time (SketchUp sandbox or browser).
"""
import json, os, sys
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import RecordingPen

TEXT = "DRONE TRG COMPLEX - 44 DIV"
font = TTFont(os.path.join(os.path.dirname(__file__), '..', 'build', 'cache', 'Arialbd.TTF'))
gs, cmap = font.getGlyphSet(), font.getBestCmap()
CAP = getattr(font['OS/2'], 'sCapHeight', 0) or 1466

def flatten(ops, steps=5):
    contours, cur = [], []
    for op, args in ops:
        if op == 'moveTo': cur = [args[0]]
        elif op == 'lineTo': cur.append(args[0])
        elif op == 'qCurveTo':
            pts = list(args); start = cur[-1]
            # implied on-curve points between consecutive off-curve points
            offs, end = pts[:-1], pts[-1]
            segs = []
            for i, o in enumerate(offs):
                e = end if i == len(offs) - 1 else ((o[0] + offs[i + 1][0]) / 2, (o[1] + offs[i + 1][1]) / 2)
                segs.append((o, e))
            for o, e in segs:
                for k in range(1, steps + 1):
                    t = k / steps
                    cur.append(((1 - t) ** 2 * start[0] + 2 * (1 - t) * t * o[0] + t * t * e[0],
                                (1 - t) ** 2 * start[1] + 2 * (1 - t) * t * o[1] + t * t * e[1]))
                start = e
        elif op in ('closePath', 'endPath'):
            if len(cur) > 2:
                if cur[0] == cur[-1]: cur = cur[:-1]
                contours.append(cur)
            cur = []
    return contours

def area(p): return sum(p[i][0] * p[(i + 1) % len(p)][1] - p[(i + 1) % len(p)][0] * p[i][1] for i in range(len(p))) / 2
def inside(pt, poly):
    x, y, c = pt[0], pt[1], False
    for i in range(len(poly)):
        (x1, y1), (x2, y2) = poly[i], poly[i - 1]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1: c = not c
    return c

out = {}
for ch in sorted(set(TEXT)):
    g = gs[cmap[ord(ch)]]
    pen = RecordingPen(); g.draw(pen)
    cs = [[(round(x / CAP, 3), round(y / CAP, 3)) for x, y in c] for c in flatten(pen.value)]
    # TrueType: outer contours clockwise (negative area), holes counter-clockwise
    outers = [c for c in cs if area(c) < 0]; holes = [c for c in cs if area(c) > 0]
    shapes = [[o[::-1], []] for o in outers]                     # store outer CCW
    for h in holes:
        for s in shapes:
            if inside(h[0], s[0]): s[1].append(h[::-1]); break     # store hole CW
    out[ch] = [round(g.width / CAP, 3), shapes]

src = '# Arial Bold outlines (cap height 1.0) for the title. Generated by make_glyphs.py\nGLYPHS = ' + json.dumps(out, separators=(',', ':')).replace('[', '[').replace('"', "'") + '\n'
open(os.path.join(os.path.dirname(__file__), 'glyphs_arialbd.py'), 'w').write(src)
print(len(src), 'bytes;', {k: (len(v[1]), sum(len(s[0]) + sum(len(h) for h in s[1]) for s in v[1])) for k, v in out.items()})
